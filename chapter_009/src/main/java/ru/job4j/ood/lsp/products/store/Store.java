package ru.job4j.ood.lsp.products.store;

import ru.job4j.ood.lsp.products.model.Food;
import java.time.LocalDate;
import java.util.List;

/**
 * Интерфейс, описывающий контракт хранилища продуктов.
 * 
 * Соблюдение LSP (Liskov Substitution Principle):
 * 1. Любая реализация Store должна корректно работать через общие методы add(),
 * accept(), getAll() и clear().
 * 2. Клиенты (например, ControlQuality) работают с типом Store, не зная точного
 * типа реализации.
 * 3. Наследники не должны усиливать предусловия (например, запрещать
 * определенные типы еды) или ослаблять постусловия.
 */
public interface Store {
    /**
     * Добавляет продукт в хранилище, привязываясь к указанной дате.
     *
     * @param food продукт для добавления.
     * @param now  дата добавления (используется для применения специфичной логики,
     *             например, скидок).
     * @return true, если продукт добавлен успешно, иначе false.
     */
    boolean add(Food food, LocalDate now);

    /**
     * Проверяет, подходит ли данный продукт для данного хранилища на указанную дату.
     * Метод выделяет условия отбора в саму сущность хранилища.
     * Это избавляет ControlQuality от необходимости проверять тип хранилища
     * или использовать instanceof, тем самым соблюдая LSP.
     *
     * @param food продукт.
     * @param now  текущая дата.
     * @return true, если продукт подходит, иначе false.
     */
    boolean accept(Food food, LocalDate now);

    /**
     * Возвращает все продукты, находящиеся в хранилище.
     *
     * @return список продуктов.
     */
    List<Food> getAll();

    /**
     * Очищает хранилище от всех продуктов.
     */
    void clear();
}
